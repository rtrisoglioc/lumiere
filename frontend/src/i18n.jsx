const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem("lumiere_lang") || "en");
  const toggle = useCallback(() => {
    setLang((l) => {
      const next = l === "en" ? "es" : "en";
      localStorage.setItem("lumiere_lang", next);
      return next;
    });
  }, []);
  const t = useCallback((key) => DICT[lang][key] ?? key, [lang]);
  return <I18nContext.Provider value={{ lang, setLang, toggle, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
